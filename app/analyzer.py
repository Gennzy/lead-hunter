def _calc_hotness(score: int, urgency: str = "low", budget: str = None,
                   timeline: str = None, readiness: str = None) -> str:
    """Calculate lead hotness: hot / warm / cold based on multiple signals."""
    if score >= 90 and urgency == "high":
        return "hot"
    if score >= 85 and urgency in ("high", "medium"):
        return "hot"
    if score >= 80:
        if budget in ("estimate", "high") or timeline == "asap" or readiness == "ready":
            return "hot"
        if urgency == "high" or readiness == "planning":
            return "warm"
    if score >= 75:
        if budget in ("estimate", "high") or timeline in ("asap", "1_3_months"):
            return "warm"
        if readiness in ("ready", "planning"):
            return "warm"
    if score >= 70:
        if budget in ("estimate", "high") and timeline in ("asap", "1_3_months"):
            return "warm"
    return "cold"


