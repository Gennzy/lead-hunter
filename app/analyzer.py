def _estimate_price(text: str, topic: str, tenant_config) -> Optional[str]:
    """Generate a rough price estimate based on tenant price list and lead params."""
    price_list = getattr(tenant_config, 'price_list', None)
    if not price_list:
        return None
    
    lower = text.lower()
    
    # Extract area if mentioned
    area = None
    area_match = re.search(r'(\d+)\s*(м2|м\.?кв|кв\.?\s*м|квадрат)', lower)
    if area_match:
        area = int(area_match.group(1))
    
    # Map topics to price keys
    topic_price_map = {
        'bathroom': ['ванная', 'ванн'],
        'kitchen': ['кухн'],
        'balcony': ['балкон', 'лоджи'],
        'doors': ['двер'],
        'windows': ['окн'],
        'tiles': ['плитк', 'керамогранит'],
        'flooring': ['ламинат', 'паркет', 'пол'],
        'walls': ['стен', 'обои', 'покраск'],
        'ceiling': ['потолк'],
        'electric': ['электрик', 'проводк', 'розетк'],
        'plumbing': ['сантехник'],
        'design': ['дизайн', 'проект'],
    }
    
    # Find matching price category
    for price_key, keywords in topic_price_map.items():
        if any(kw in lower for kw in keywords):
            if price_key in price_list:
                prices = price_list[price_key]
                min_price = prices.get('min', 0)
                max_price = prices.get('max', 0)
                unit = prices.get('unit', '₽/м²')
                
                if min_price and max_price:
                    if area:
                        total_min = min_price * area
                        total_max = max_price * area
                        return f"~{total_min:,.0f}–{total_max:,.0f} ₽ ({min_price}–{max_price} {unit} × {area} м²)"
                    else:
                        return f"{min_price}–{max_price} {unit}"
    
    return None


