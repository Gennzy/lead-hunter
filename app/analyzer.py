_openai_client = None
_active_key_idx = 0


def _get_providers() -> list:
    """Configured LLM providers: [(api_key, base_url, model), ...]."""
    providers = []
    if settings.openai_api_key:
        providers.append((settings.openai_api_key, settings.openai_base_url, settings.openai_model))
    key2 = getattr(settings, "openai_api_key_2", "") or ""
    if key2:
        base2 = getattr(settings, "openai_base_url_2", "") or settings.openai_base_url
        model2 = getattr(settings, "openai_model_2", "") or settings.openai_model
        providers.append((key2, base2, model2))
    return providers


def _get_openai_client():
    global _openai_client
    providers = _get_providers()
    if not providers:
        return None
    idx = min(_active_key_idx, len(providers) - 1)
    if _openai_client is None:
        key, base_url, _model = providers[idx]
        _openai_client = AsyncOpenAI(
            api_key=key,
            base_url=base_url,
            max_retries=2,
            timeout=15.0,
        )
    return _openai_client


def _active_model() -> str:
    providers = _get_providers()
    idx = min(_active_key_idx, len(providers) - 1)
    return providers[idx][2] if providers else settings.openai_model


def _rotate_api_key():
    """Switch to the next configured provider (if any) and rebuild the client."""
    global _openai_client, _active_key_idx
    providers = _get_providers()
    if len(providers) < 2:
        return False
    _active_key_idx = (_active_key_idx + 1) % len(providers)
    _openai_client = None
    logger.info("Rotated LLM provider -> #%d (%s)", _active_key_idx + 1, providers[_active_key_idx][1])
    return True


