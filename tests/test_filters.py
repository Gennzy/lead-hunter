class TestFalsePositiveFilters(unittest.TestCase):
    def test_bad_messages_rejected(self):
        failed = []
        for name, text in BAD_CASES.items():
            result = _keyword_score(text)
            if result["is_lead"]:
                failed.append((name, result["lead_score"], result["reason"]))
        self.assertEqual(
            failed, [],
            f"Ложные срабатывания (должны быть отбракованы): {failed}",
        )

    def test_good_messages_pass(self):
        failed = []
        for name, text in GOOD_CASES.items():
            result = _keyword_score(text)
            if not result["is_lead"]:
                failed.append((name, result["reason"]))
        self.assertEqual(
            failed, [],
            f"Реальные лиды отбракованы фильтрами: {failed}",
        )

    def test_scores_in_range(self):
        for text in list(BAD_CASES.values()) + list(GOOD_CASES.values()):
            result = _keyword_score(text)
            self.assertIsInstance(result["is_lead"], bool)
            self.assertTrue(0 <= result["lead_score"] <= 100)


