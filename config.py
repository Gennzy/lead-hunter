def utcnow() -> datetime:
    """Return current UTC time as a naive datetime (backward-compatible with datetime.utcnow())."""
    return datetime.now(timezone.utc).replace(tzinfo=None)

_ENV_FILE = Path(".env")


def _get_or_create_secret(key_name: str, default: str = "") -> str:
    """Read a secret from .env, or generate and persist it if missing."""
    if _ENV_FILE.exists():
        for line in _ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith(f"{key_name}=") and not line.startswith(f"{key_name}_"):
                val = line.split("=", 1)[1].strip().strip('"').strip("'")
                if val and val != "change-me":
                    return val
    generated = secrets.token_hex(32)
    with open(_ENV_FILE, "a", encoding="utf-8") as f:
        f.write(f"\n{key_name}={generated}\n")
    return generated


def _get_or_create_db_secret() -> str:
    """Read POSTGRES_PASSWORD from .env, or generate and persist it if missing."""
    if _ENV_FILE.exists():
        for line in _ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith("POSTGRES_PASSWORD="):
                val = line.split("=", 1)[1].strip().strip('"').strip("'")
                if val and val != "change-me":
                    return val
    generated = secrets.token_hex(32)
    with open(_ENV_FILE, "a", encoding="utf-8") as f:
        f.write(f"\nPOSTGRES_PASSWORD={generated}\n")
    return generated


